import { RuckigError } from "./error";
import type { Bound } from "./profile";
import { Profile } from "./profile";
import { integrate } from "./utils";

/** The index of the first element of the ascending `values` that is greater than `value`: C++'s std::upper_bound. */
function upperBound(values: readonly number[], value: number): number {
  let first = 0;
  let count = values.length;
  while (count > 0) {
    const step = Math.floor(count / 2);
    const middle = first + step;
    if (!(value < values[middle])) {
      first = middle + 1;
      count -= step + 1;
    } else {
      count = step;
    }
  }
  return first;
}

/** The trajectory generated by the Ruckig algorithm. */
export class Trajectory {
  readonly degreesOfFreedom: number;

  /**
   * The profiles of each section and coordinate. The community edition has one section. The calculator writes
   * here; read the copies `profiles` gives.
   * @internal
   */
  readonly _profiles: Profile[][];
  /** @internal */
  _duration: number = 0.0;
  /** @internal */
  readonly _cumulativeTimes: number[] = [0.0];
  /** @internal */
  readonly _independentMinDurations: number[];
  private readonly _positionExtrema: Bound[];

  constructor(dofs: number) {
    this.degreesOfFreedom = dofs;
    this._profiles = [Array.from({ length: dofs }, () => new Profile())];
    this._independentMinDurations = new Array<number>(dofs).fill(0.0);
    this._positionExtrema = Array.from({ length: dofs }, () => ({ min: 0.0, max: 0.0, tMin: 0.0, tMax: 0.0 }));
  }

  /**
   * Calculates the base values to then integrate from: calls `set_integrate` for every coordinate with the time
   * since the start of its phase and the state and jerk there, and returns the section.
   */
  private stateToIntegrateFrom(time: number, set_integrate: (dof: number, t: number, p: number, v: number, a: number, j: number) => void): number {
    const profiles = this._profiles;
    const cumulative_times = this._cumulativeTimes;

    if (time >= this._duration) {
      // Keep constant acceleration
      const new_section = profiles.length;
      const profiles_dof = profiles[profiles.length - 1];
      for (let dof = 0; dof < this.degreesOfFreedom; ++dof) {
        const t_pre = (profiles.length > 1) ? cumulative_times[cumulative_times.length - 2] : profiles_dof[dof].brake.duration;
        const t_diff = time - (t_pre + profiles_dof[dof].tSum[6]);
        set_integrate(dof, t_diff, profiles_dof[dof].p[7], profiles_dof[dof].v[7], profiles_dof[dof].a[7], 0.0);
      }
      return new_section;
    }

    const new_section = upperBound(cumulative_times, time);
    let t_diff = time;
    if (new_section > 0) {
      t_diff -= cumulative_times[new_section - 1];
    }

    for (let dof = 0; dof < this.degreesOfFreedom; ++dof) {
      const p = profiles[new_section][dof];
      let t_diff_dof = t_diff;

      // Brake pre-trajectory
      if (new_section === 0 && p.brake.duration > 0) {
        if (t_diff_dof < p.brake.duration) {
          const index = (t_diff_dof < p.brake.t[0]) ? 0 : 1;
          if (index > 0) {
            t_diff_dof -= p.brake.t[index - 1];
          }

          set_integrate(dof, t_diff_dof, p.brake.p[index], p.brake.v[index], p.brake.a[index], p.brake.j[index]);
          continue;
        } else {
          t_diff_dof -= p.brake.duration;
        }
      }

      // Non-time synchronization
      if (t_diff_dof >= p.tSum[6]) {
        // Keep constant acceleration
        set_integrate(dof, t_diff_dof - p.tSum[6], p.p[7], p.v[7], p.a[7], 0.0);
        continue;
      }

      const index_dof = upperBound(p.tSum, t_diff_dof);

      if (index_dof > 0) {
        t_diff_dof -= p.tSum[index_dof - 1];
      }

      set_integrate(dof, t_diff_dof, p.p[index_dof], p.v[index_dof], p.a[index_dof], p.j[index_dof]);
    }

    return new_section;
  }

  /**
   * Writes the kinematic state and the jerk at a given time into the four vectors, and returns the section.
   * @internal
   */
  _atTimeInto(time: number, new_position: number[], new_velocity: number[], new_acceleration: number[], new_jerk: number[]): number {
    const dofs = this.degreesOfFreedom;
    if (dofs !== new_position.length || dofs !== new_velocity.length || dofs !== new_acceleration.length || dofs !== new_jerk.length) {
      throw new RuckigError("mismatch in degrees of freedom (vector size).");
    }

    return this.stateToIntegrateFrom(time, (dof, t, p, v, a, j) => {
      [new_position[dof], new_velocity[dof], new_acceleration[dof]] = integrate(t, p, v, a, j);
      new_jerk[dof] = j;
    });
  }

  /**
   * Get the kinematic state at a given time: the position, the velocity and the acceleration of every coordinate,
   * and after them the section if `returnSection`. Past the end of the trajectory the final acceleration is kept.
   */
  atTime(time: number): [number[], number[], number[]];
  atTime(time: number, returnSection: false): [number[], number[], number[]];
  atTime(time: number, returnSection: true): [number[], number[], number[], number];
  atTime(time: number, returnSection: boolean = false): [number[], number[], number[]] | [number[], number[], number[], number] {
    const zeros = (): number[] => new Array<number>(this.degreesOfFreedom).fill(0.0);
    const new_position = zeros();
    const new_velocity = zeros();
    const new_acceleration = zeros();
    const new_section = this._atTimeInto(time, new_position, new_velocity, new_acceleration, zeros());
    if (returnSection) {
      return [new_position, new_velocity, new_acceleration, new_section];
    }
    return [new_position, new_velocity, new_acceleration];
  }

  /** Get the underlying profiles of the trajectory: a copy, one list of the coordinates' profiles a section. */
  get profiles(): Profile[][] {
    return this._profiles.map((section) => section.map((profile) => profile.clone()));
  }

  /** Get the duration of the (synchronized) trajectory */
  get duration(): number {
    return this._duration;
  }

  /** Get the durations when the intermediate waypoints are reached */
  get intermediateDurations(): number[] {
    return this._cumulativeTimes.slice();
  }

  /** Get the minimum duration of each independent DoF */
  get independentMinDurations(): number[] {
    return this._independentMinDurations.slice();
  }

  /** Get the min/max values of the position for each DoF */
  get positionExtrema(): Bound[] {
    const profiles = this._profiles;
    const position_extrema = this._positionExtrema;

    for (let dof = 0; dof < this.degreesOfFreedom; ++dof) {
      position_extrema[dof] = profiles[0][dof].getPositionExtrema();
    }

    for (let i = 1; i < profiles.length; ++i) {
      for (let dof = 0; dof < this.degreesOfFreedom; ++dof) {
        const section_position_extrema = profiles[i][dof].getPositionExtrema();
        if (section_position_extrema.max > position_extrema[dof].max) {
          position_extrema[dof].max = section_position_extrema.max;
          position_extrema[dof].tMax = section_position_extrema.tMax;
        }
        if (section_position_extrema.min < position_extrema[dof].min) {
          position_extrema[dof].min = section_position_extrema.min;
          position_extrema[dof].tMin = section_position_extrema.tMin;
        }
      }
    }

    return position_extrema.map((bound) => ({ ...bound }));
  }

  /**
   * Get the time that this trajectory passes a specific position of a given DoF the first time; undefined if it
   * never does (the Python module's None).
   */
  getFirstTimeAtPosition(dof: number, position: number, timeAfter: number = 0.0): number | undefined {
    if (dof >= this.degreesOfFreedom) {
      return undefined;
    }

    const profiles = this._profiles;
    for (let i = 0; i < profiles.length; ++i) {
      const time = profiles[i][dof].getFirstStateAtPosition(position, timeAfter);
      if (time !== undefined) {
        const section_time = (i > 0) ? this._cumulativeTimes[i - 1] : 0.0;
        return section_time + time;
      }
    }
    return undefined;
  }
}
