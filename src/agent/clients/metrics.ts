// Ports pear/deploy/station/agent_loop/clients/metrics.py: the timings and the token rates of a model request, as
// its performance events hold them.
//
// Python tells a whole number (int) from a float and a boolean from both; JavaScript has one number type. Here a
// number counts as Python's int when it is a whole number, so a count a server sends as 20.0 is taken where PEAR
// leaves it out; a boolean is never a number, as in PEAR.

import { monotonic, type Clock } from "../clock";
import type { EventData, Usage } from "./schemas";

/** Where a model request stands, each by the word its performance events carry. */
export const RequestStatus = {
  /** Its answer still comes. */
  STREAMING: "streaming",
  /** It ended with the answer. */
  COMPLETED: "completed",
  /** A stop ended it. */
  INTERRUPTED: "interrupted",
  /** It ended without an answer. */
  FAILED: "failed",
} as const;
export type RequestStatus = (typeof RequestStatus)[keyof typeof RequestStatus];

/** Whether ``value`` is what Python calls an int: a whole number, and no boolean. */
export function isPythonInt(value: unknown): value is number {
  return typeof value === "number" && Number.isInteger(value);
}

/**
 * Python 3.12's sum() of numbers: the whole numbers that come first add up exactly, and from the first float on
 * each float is added with Neumaier's compensation (CPython, Python/bltinmodule.c), a whole number plainly.
 */
export function pythonSum(values: readonly number[]): number {
  let index = 0;
  let total = 0;
  while (index < values.length && Number.isInteger(values[index])) {
    total += values[index]!;
    index += 1;
  }
  if (index === values.length) {
    return total;
  }

  total += values[index]!;
  let compensation = 0;
  for (index += 1; index < values.length; index++) {
    const value = values[index]!;
    if (Number.isInteger(value)) {
      total += value;
      continue;
    }
    const sum = total + value;
    compensation += Math.abs(total) >= Math.abs(value) ? total - sum + value : value - sum + total;
    total = sum;
  }
  // (a compensation that is infinite or no number would turn an overflowed sum into no number)
  if (compensation && Number.isFinite(compensation)) {
    total += compensation;
  }

  return total;
}

/** The timings and the decode throughput of one model request, as its performance events hold them. */
export const Performance = {
  /** Returns the timings a client observed of a request that began at ``startTime``, read on ``clock`` now. */
  report(
    provider: string,
    startTime: number,
    firstOutputS: number | null,
    usage: Usage,
    options: { status?: RequestStatus; clock?: Clock } = {},
  ): EventData {
    const status = options.status ?? RequestStatus.COMPLETED;
    const elapsedS = (options.clock ?? monotonic)() - startTime;
    const outputTokens = usage.output ?? null;

    return {
      backend: provider,
      first_visible_output_s: firstOutputS,
      elapsed_s: elapsedS,
      output_tokens: outputTokens,
      output_throughput_tps: outputTokens !== null && elapsedS > 0 ? outputTokens / elapsedS : null,
      final: status !== RequestStatus.STREAMING,
      status,
    };
  },

  /**
   * Returns the decode rate on the server's clock of (tokens, milliseconds) samples, null for both of its numbers
   * when a sample is unusable.
   */
  decodeRate(samples: ReadonlyArray<readonly [unknown, unknown]>): {
    decode_throughput_tps: number | null;
    decode_time_s: number | null;
  } {
    const noRate = { decode_throughput_tps: null, decode_time_s: null };
    if (samples.length === 0) {
      return noRate;
    }

    for (const [tokens, milliseconds] of samples) {
      if (
        typeof milliseconds !== "number" ||
        !Number.isFinite(milliseconds) ||
        milliseconds <= 0 ||
        !isPythonInt(tokens) ||
        tokens <= 1
      ) {
        return noRate;
      }
    }

    const seconds = pythonSum(samples.map(([, milliseconds]) => milliseconds as number)) / 1000;

    // the first token ends the prefill: only the others are decoded
    return {
      decode_throughput_tps: pythonSum(samples.map(([tokens]) => (tokens as number) - 1)) / seconds,
      decode_time_s: seconds,
    };
  },
};

/** The tokens a second, on the client's clock, between the first and the last usage report of each request. */
export class TokenRate {
  // request id -> [[the first count, when it came], [the last count, when it came]]
  private readonly samples = new Map<string, [[number, number], [number, number]]>();

  /** Takes the tokens a request has generated by ``receivedAt``; a count that is no whole number above zero is
   * left out. */
  add(requestId: string, tokenCount: unknown, receivedAt: number): void {
    if (!isPythonInt(tokenCount) || tokenCount <= 0) {
      return;
    }

    const sample = this.samples.get(requestId);
    if (sample === undefined) {
      this.samples.set(requestId, [
        [tokenCount, receivedAt],
        [tokenCount, receivedAt],
      ]);
    } else if (tokenCount > sample[1][0]) {
      sample[1] = [tokenCount, receivedAt];
    }
  }

  /** Returns the rate over the requests whose reports span some time, null when no request's do. */
  tokensPerSecond(): number | null {
    const spans = [...this.samples.values()]
      .filter(([firstReport, lastReport]) => lastReport[1] > firstReport[1])
      .map(([firstReport, lastReport]) => [lastReport[0] - firstReport[0], lastReport[1] - firstReport[1]] as const);
    const seconds = pythonSum(spans.map(([, span]) => span));

    return seconds ? pythonSum(spans.map(([tokens]) => tokens)) / seconds : null;
  }
}
